const state = reactive({
    lang: localStorage.getItem('lang') || 'fr',
})

const direction = computed(() => (state.lang === 'ar' ? 'rtl' : 'ltr'))

function applyDocumentAttributes() {
    if (typeof document !== 'undefined') {
        document.documentElement.lang = state.lang
        document.documentElement.dir = direction.value
    }
}

function setLang(code) {
    const isValid = languages.some((l) => l.code === code)
    state.lang = isValid ? code : 'fr'
    localStorage.setItem('lang', state.lang)
    applyDocumentAttributes()
}

function getValue(path, langCode = state.lang) {
    const parts = path.split('.')
    let value = translations[langCode]
    for (const part of parts) {
        value = value?.[part]
        if (value === undefined) break
    }
    if (value === undefined && langCode !== 'fr') {
        return getValue(path, 'fr')
    }
    return value ?? path
}

function t(path, vars = {}) {
    const value = getValue(path)
    if (typeof value === 'string') {
        return value.replace(/\{(\w+)\}/g, (_, key) => (vars[key] !== undefined ? vars[key] : `{${key}}`))
    }
    return value
}

const i18n = {
    languages,
    translations,
    lang: computed(() => state.lang),
    direction,
    setLang,
    t,
    applyDocumentAttributes,
}

applyDocumentAttributes()

export function useI18n() {
    return inject('i18n', i18n)
}

export default i18n
